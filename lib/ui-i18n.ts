function dynamicTranslation(value: string) {
  let match: RegExpMatchArray | null;

  if ((match = value.match(/^官方技能\s*\((\d+)\)$/))) return `Built-in (${match[1]})`;
  if ((match = value.match(/^我的技能\s*\((\d+)\)$/))) return `My skills (${match[1]})`;
  if ((match = value.match(/^已导入\s*\((\d+)\)$/))) return `Imported (${match[1]})`;
  if ((match = value.match(/^来源证据\s*(\d+)$/))) return `Source evidence ${match[1]}`;
  if ((match = value.match(/^知识库状态：\s*(已连接|未配置)$/))) return `Knowledge base status: ${match[1] === "已连接" ? "Connected" : "Not configured"}`;
  if ((match = value.match(/^([\d…—]+)\s*个节点\s*·\s*([\d…—]+)\s*条关系$/))) return `${match[1]} nodes · ${match[2]} relationships`;
  if ((match = value.match(/^([\d…—]+)\s*条消息\s*·\s*([\d…—]+)\s*个来源$/))) return `${match[1]} messages · ${match[2]} sources`;
  if ((match = value.match(/^([\d…—]+)\s*个来源$/))) return `${match[1]} sources`;
  if ((match = value.match(/^([\d…—]+)\s*个本机 Session$/))) return `${match[1]} browser sessions`;
  if ((match = value.match(/^([\d…—]+)\s*个 Workspace$/))) return `${match[1]} Workspaces`;
  if ((match = value.match(/^([\d…—]+)\s*篇结果$/))) return `${match[1]} results`;
  if ((match = value.match(/^找到\s*([\d,.…—]+)\s*篇$/))) return `${match[1]} articles found`;
  if ((match = value.match(/^“(.+)”的搜索结果$/))) return `Search results for “${match[1]}”`;
  if ((match = value.match(/^作者：(.+)$/))) return `Author: ${match[1]}`;
  if ((match = value.match(/^发布日期：(.+)$/))) return `Published: ${match[1]}`;
  if ((match = value.match(/^来源\s*(\d+)\s*·\s*(.+)$/))) return `Source ${match[1]} · ${match[2]}`;
  if ((match = value.match(/^技能：(.+)$/))) return `Skill: ${translateUiText(match[1])}`;
  if ((match = value.match(/^已选择：(.+)$/))) return `Selected: ${translateUiText(match[1])}`;
  if ((match = value.match(/^已选择\s*(\d+)\/(\d+)$/))) return `Selected ${match[1]}/${match[2]}`;
  if ((match = value.match(/^已识别\s*(\d+)\s*个字段，请确认后再填写。$/))) return `${match[1]} fields detected. Confirm them before filling.`;
  if ((match = value.match(/^正在检索“(.+)”并填写\s*(\d+)\s*个字段…$/))) return `Searching “${match[1]}” and filling ${match[2]} fields…`;
  if ((match = value.match(/^已按你确认的\s*(\d+)\s*个字段生成文件。请先核对预览与来源事实，再下载使用。$/))) return `A file has been generated for the ${match[1]} confirmed fields. Review the preview and source facts before downloading and using it.`;
  if ((match = value.match(/^已自动隐藏\s*(\d+)\s*个恢复后已不存在的旧 Workspace 配置。$/))) return `${match[1]} obsolete Workspace configurations that no longer exist after restore were hidden automatically.`;
  if ((match = value.match(/^已自动隐藏\s*(\d+)\s*个在恢复后的 AnythingLLM 中已不存在的旧 Workspace 配置。$/))) return `${match[1]} obsolete Workspace configurations missing from the restored AnythingLLM were hidden automatically.`;
  if ((match = value.match(/^快速反馈\s*(\d+)$/))) return `Quick feedback ${match[1]}`;
  if ((match = value.match(/^·?\s*原型问卷\s*(\d+)$/))) return `· Prototype survey ${match[1]}`;
  if ((match = value.match(/^(\d+)\/(\d+)\s*项已评分$/))) return `${match[1]}/${match[2]} rated`;
  if ((match = value.match(/^表：(.+)$/))) return `Table: ${match[1]}`;
  if ((match = value.match(/^(.+)\s*页（请求\s*(.+)\s*页）\s*·\s*本次检索使用\s*(.+)\s*个来源。$/))) return `${match[1]} slides (requested ${match[2]}) · ${match[3]} sources retrieved.`;
  if ((match = value.match(/^(.+)\s*个变更，(.+)\s*个失败。$/))) return `${match[1]} changes, ${match[2]} failed.`;
  if ((match = value.match(/^同步完成：(.+)$/))) return `Sync complete: ${match[1]}`;
  if ((match = value.match(/^错误：(.+)$/))) return `Error: ${match[1]}`;

  return null;
}

function withIconPrefix(value: string) {
  const match = value.match(/^([^\p{L}\p{N}\u3400-\u9fff]*)(.+)$/u);
  if (!match || !match[1]) return null;
  const translated = dictionary.get(match[2]) || dynamicTranslation(match[2]);
  return translated ? `${match[1]}${translated}` : null;
}

export function translateUiText(value: string) {
  const trimmed = value.trim();
  if (!trimmed) return value;
  return dictionary.get(trimmed) || dynamicTranslation(trimmed) || withIconPrefix(trimmed) || trimmed;
}

export function containsChineseUi(value: string) {
  return /[\u3400-\u9fff]/u.test(value);
}
